#!/bin/bash
# Chạy trên node RHEL 9 (cần sudo). Mỗi mục in tiêu đề + lệnh kiểm tra để chụp ảnh / lưu file.
# Cách chạy từ WSL, lưu kết quả vào file:
#   ssh ansible@192.168.221.101 'sudo bash -s' < verify_cis.sh | tee results/rhel-node1_verify.txt
h() { echo; echo "===== $1 ====="; }
r() { echo "\$ $*"; bash -c "$*" 2>&1; }

h "1.2.1.2 gpgcheck (dnf.conf + moi kho trong /etc/yum.repos.d)"
r "grep -rEhi '^\s*gpgcheck\s*=' /etc/dnf/dnf.conf /etc/yum.repos.d/ | sed 's/ //g' | sort | uniq -c"
r "echo \"so kho phan mem: \$(cat /etc/yum.repos.d/*.repo | grep -c '^\[')\""
r "grep -rEi '^\s*gpgcheck\s*=\s*(0|false|no)\s*\$' /etc/dnf/ /etc/yum.repos.d/; echo \"ma thoat=\$? (1 = khong co dong nao gpgcheck=0)\""
h "1.3.1.5 SELinux"
r "grep -E '^SELINUX=' /etc/selinux/config"; r "getenforce"
h "1.5.6 randomize_va_space"
r "sysctl kernel.randomize_va_space"; r "grep -rs randomize_va_space /etc/sysctl.conf /etc/sysctl.d/"
h "1.6.1 crypto policy"
r "update-crypto-policies --show"; r "cat /etc/crypto-policies/config"
h "2.1.15 telnet-server"
r "rpm -q telnet-server"; r "systemctl is-enabled telnet.socket"
h "2.2.3 telnet client"
r "rpm -q telnet"
h "2.3.1 chrony installed"
r "rpm -q chrony"
h "2.3.2 chrony configured"
r "grep -hE '^(server|pool)' /etc/chrony.conf /etc/chrony.d/*.conf 2>/dev/null"
r "chronyc sources"
r "chronyc tracking | grep -E 'Reference ID|Stratum|Leap status'"
h "2.4.1.1 crond"
r "systemctl is-enabled crond"; r "systemctl is-active crond"
h "3.1.3 bluetooth"
r "rpm -q bluez"
h "3.3.1.1 ip_forward"
r "sysctl net.ipv4.ip_forward"; r "grep -rs 'net.ipv4.ip_forward' /etc/sysctl.conf /etc/sysctl.d/"
h "3.3.1.12 rp_filter"
r "sysctl net.ipv4.conf.all.rp_filter"; r "grep -rs 'net.ipv4.conf.all.rp_filter' /etc/sysctl.conf /etc/sysctl.d/"
h "3.3.1.18 tcp_syncookies"
r "sysctl net.ipv4.tcp_syncookies"; r "grep -rs 'net.ipv4.tcp_syncookies' /etc/sysctl.conf /etc/sysctl.d/"
h "4.1.1 firewalld installed"
r "rpm -q firewalld"
h "4.1.3 firewalld service"
r "systemctl is-enabled firewalld"; r "systemctl is-active firewalld"
h "4.1.9 conflicting firewall utilities"
r "systemctl is-enabled nftables"; r "systemctl is-active nftables"; r "rpm -q iptables-services ufw"
h "4.1.10 firewalld log denied"
r "firewall-cmd --get-log-denied"
h "5.1.20 PermitEmptyPasswords"
r "grep -RniE '^\s*Match\b' /etc/ssh/sshd_config /etc/ssh/sshd_config.d/; echo \"ma thoat=\$? (1 = khong co khoi Match)\""
r "sshd -T -C user=root,host=localhost,addr=127.0.0.1 | grep -i permitemptypasswords"
r "sshd -T -C user=ansible,host=localhost,addr=127.0.0.1 | grep -i permitemptypasswords"
h "5.1.21 PermitRootLogin"
r "grep -RniE '^\s*Match\b' /etc/ssh/sshd_config /etc/ssh/sshd_config.d/; echo \"ma thoat=\$? (1 = khong co khoi Match)\""
r "sshd -T -C user=root,host=localhost,addr=127.0.0.1 | grep -i permitrootlogin"
r "sshd -T -C user=ansible,host=localhost,addr=127.0.0.1 | grep -i permitrootlogin"
h "5.2.4 sudo use_pty"
r "grep -rHE '^\s*Defaults\s+.*use_pty' /etc/sudoers /etc/sudoers.d/"
r "grep -rHE '^\s*Defaults\s+!use_pty' /etc/sudoers /etc/sudoers.d/ || echo 'Khong co !use_pty'"
h "5.3.3.1.1 faillock deny"
r "grep -E '^\s*deny' /etc/security/faillock.conf"
r "grep -nE 'deny\s*=' /etc/pam.d/system-auth /etc/pam.d/password-auth; echo \"ma thoat=\$? (1 = PAM khong ghi de deny)\""
r "authselect current"
h "5.3.3.2.2 pwquality minlen"
r "grep -E '^\s*minlen' /etc/security/pwquality.conf"
r "grep -rnE '^\s*minlen' /etc/security/pwquality.conf.d/; echo \"ma thoat=\$? (1 = khong co ghi de trong pwquality.conf.d)\""
r "grep -nE 'minlen\s*=' /etc/pam.d/system-auth /etc/pam.d/password-auth; echo \"ma thoat=\$? (1 = PAM khong ghi de minlen)\""
h "6.1.2.2 rsyslog"
r "systemctl is-enabled rsyslog"; r "systemctl is-active rsyslog"
h "6.2.1.4 auditd"
r "systemctl is-enabled auditd"; r "systemctl is-active auditd"
h "6.2.2.2 audit logs keep"
r "grep -E '^\s*max_log_file_action' /etc/audit/auditd.conf"
h "6.2.3.2 user_emulation"
r "grep -h user_emulation /etc/audit/rules.d/*.rules"; r "auditctl -l | grep user_emulation"
h "6.3.2 AIDE"
r "rpm -q aide"; r "crontab -l | grep -i aide"
h "7.1.1 /etc/passwd"
r "stat -c '%a %U:%G %n' /etc/passwd"
h "7.1.5 /etc/shadow"
r "stat -c '%a %U:%G %n' /etc/shadow"
h "7.1.11 world writable"
r "df --local -P | awk 'NR!=1 {print \$6}' | xargs -I@ find @ -xdev -type f -perm -0002"
r "df --local -P | awk 'NR!=1 {print \$6}' | xargs -I@ find @ -xdev -type d -perm -0002 ! -perm -1000"
echo "(Khong in gi o 2 lenh tren la dat)"
h "7.2.8 home directories (moi tai khoan co shell dang nhap hop le, moi UID)"
r "getent passwd | awk -F: '\$7!~/(nologin|false)\$/ {print \$1\" UID=\"\$3\" shell=\"\$7\" home=\"\$6}'"
r "awk -F: -v re=\"^(\$(grep -E '^/' /etc/shells | grep -vE '(nologin|false)\$' | paste -sd'|'))\$\" '\$7 ~ re {print \$1\":\"\$6}' /etc/passwd | while IFS=: read u d; do stat -c '%a %U:%G %n' \"\$d\"; done"

